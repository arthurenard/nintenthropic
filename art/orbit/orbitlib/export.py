"""glTF exports: the cupola (baked, unlit), the station (PBR), and the loose
assets (debris, drone, derelict, extras). Draco geometry, WebP textures,
contract nodes with their extras.

Blender's glTF exporter maps Blender (x, y, z) to glTF (x, z, -y) and a
node's Blender +Y axis to its glTF -Z: every "facing" empty below is built
with bl.look_matrix so its glTF -Z points where it should.
"""

import os

import bpy
from mathutils import Matrix, Vector

from dustcreek.nodes import new_material

from . import bl, world, pipeline, render

COPYRIGHT = "Nintenthropic - Orbital Decay, generated by art/orbit/build_orbit.py"


def unlit_material(name, img, uv='UVMap'):
    """Emission behind the 'Is Camera Ray' switch: what the glTF exporter
    writes as KHR_materials_unlit, and what Cycles shows as the pure baked
    colour (the review's unlit check)."""
    m, g = new_material(name)
    tex = g.image(img, g.uv(uv), out='Color', extension='EXTEND')
    em = g.node('ShaderNodeEmission', inputs={'Color': tex, 'Strength': 1.0}, out=0)
    lp = g.node('ShaderNodeLightPath', out='Is Camera Ray')
    tr = g.node('ShaderNodeBsdfTransparent', out=0)
    mix = g.node('ShaderNodeMixShader', inputs={0: lp, 1: tr, 2: em}, out=0)
    g.output(mix)
    return m


def glass_material():
    """The panes: a clean, faint, glossy glass. The game draws the cracks
    and reflections itself (see README)."""
    m, g = new_material("glass_pane")
    b = g.principled((0.86, 0.9, 0.92), rough=0.04, metal=0.0, spec=0.5, alpha=0.08)
    g.output(b)
    try:
        m.surface_render_method = 'BLENDED'
    except AttributeError:
        pass
    m.use_backface_culling = False
    return m


def strip(ob, keep_uv):
    me = ob.data
    for uv in list(me.uv_layers):
        if uv.name != keep_uv:
            me.uv_layers.remove(uv)
    if me.uv_layers:
        me.uv_layers[0].name = 'UVMap'
    for a in list(me.attributes):
        if a.name in ('rand',):
            me.attributes.remove(me.attributes[a.name])
    for c in list(me.color_attributes):
        me.color_attributes.remove(c)


def gltf_export(path, tangents=False, quality=88, draco=True, animations=False, selection=None, pos_bits=16, uv_bits=14):
    kw = dict(filepath=path, export_format='GLB', use_visible=False, use_renderable=False,
              export_extras=True, export_cameras=True, export_lights=False, export_yup=True, export_apply=True,
              export_texcoords=True, export_normals=True, export_tangents=tangents, export_materials='EXPORT',
              export_vertex_color='NONE', export_attributes=False,
              export_image_format='WEBP', export_image_quality=quality, export_image_add_webp=False,
              export_draco_mesh_compression_enable=draco, export_draco_mesh_compression_level=7,
              export_draco_position_quantization=pos_bits, export_draco_normal_quantization=10,
              export_draco_texcoord_quantization=uv_bits, export_draco_generic_quantization=12,
              export_animations=animations, export_skins=False, export_morph=False, export_unused_images=False,
              export_copyright=COPYRIGHT)
    if selection is not None:
        bpy.ops.object.select_all(action='DESELECT')
        for o in selection:
            o.select_set(True)
        kw['use_selection'] = True
    else:
        kw['use_selection'] = False
    bpy.ops.export_scene.gltf(**kw)
    print("exported", path, f"{os.path.getsize(path) / 1e6:.2f} MB", flush=True)


def contract_common(col):
    """sun, planet (and its extras) - the same in cupola.glb and station.glb."""
    s = Vector(world.sun_dir())
    bl.empty("sun", col, matrix=bl.look_matrix((0, 0, 0), -s, (0, 0, 1)), size=0.5,
             note="-Z points along the sunlight (from the sun toward the station)",
             sun_toward=[round(c, 5) for c in world.gltf(s)])
    # the planet: an empty at its centre whose axes are the planet's (Blender
    # local x = longitude 0, y = 90 E, z = north): in glTF a SphereGeometry
    # child of this node with three.js's default UVs shows the maps right.
    M = Matrix([list(r) for r in world.planet_rotation()]).to_4x4()
    M.translation = Vector(world.planet_center_km() * 1000.0)
    meta = {}
    import json
    mp = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "build", "planet_meta.json")
    if os.path.exists(mp):
        meta = json.load(open(mp))
    bl.empty("planet", col, matrix=M, size=1000.0,
             radius_m=world.R_KM * 1000.0, altitude_m=world.ALT_KM * 1000.0,
             cloud_height_m=6000.0, atmosphere_m=100000.0,
             subpoint_lonlat=list(world.SUBPOINT), heading_deg=world.HEADING_DEG,
             hi_lonlat=list(meta.get('hi', [-112.0, 47.0])),
             storm_lonlat=list(meta.get('storm', [0.0, 0.0])),
             hurricanes_lonlat=[float(c) for h in meta.get("hurricanes", []) for c in h],
             note="planet centre and axes; maps in planet/*.webp, equirect, north at the top; see art/orbit/README.md")


def station(ctx):
    """Bake the station's PBR atlas from the eye's point of view and write
    station.glb with its contract nodes."""
    from . import atlas, pbrbake
    pipeline.open_blend(pipeline.scene_blend(ctx))
    sc = bpy.context.scene
    objs = [o for o in bpy.data.collections['station'].all_objects if o.type == 'MESH']
    occl = [o for o in sc.objects if o.type == 'MESH' and not o.name.startswith('pane.')]
    dens = atlas.EyeDensity(occl, screen_h=1440, quality=1.0, floor=4.0)
    size = (4096, 4096) if not ctx.quick else (1024, 1024)
    # the cupola is not part of this file, but it shades nothing out here
    for o in bpy.data.collections['cupola'].all_objects:
        o.hide_render = True
    pbrbake.bake(ctx, "station", objs, size, dens, ao_distance=1.5, quick=ctx.quick, eye=(0.0, 0.0, 0.0),
                 samples=dict(color=8, rough=16, metal=16, normal=48, ao=96))
    for o in objs:
        pbrbake.merge_duplicate_slots(o)
        strip(o, 'bake')
        for k in ('part',):
            if k in o.keys():
                del o[k]
        if 'surface' not in o.keys():
            o['surface'] = 'metal'
    # keep: the station meshes and the contract empties (not the camera)
    keep = {o.name for o in objs} | {o.name for o in bpy.data.collections['contract'].all_objects}
    keep.discard('camera.player')
    for o in list(sc.objects):
        if o.name not in keep:
            bpy.data.objects.remove(o)
    col = bl.collection("contract_export")
    contract_common(col)
    sc["exposure_stops"] = render.EXPOSURE
    sc["sun_irradiance"] = 20.0
    sc["colors"] = ("PBR, lit at runtime: sun irradiance 20 (Blender W/m2) with the exposure in exposure_stops "
                    "reproduces the review renders; see art/orbit/README.md")
    out = ctx.asset("station.glb")
    gltf_export(out, tangents=True, quality=86)
    bpy.ops.wm.save_as_mainfile(filepath=ctx.path("station_export.blend"), compress=True)


def cupola(ctx):
    pipeline.open_blend(ctx.path("cupola_baked.blend"))
    sc = bpy.context.scene
    png = ctx.path("cupola_atlas.png")
    img = bpy.data.images.load(png, check_existing=False)
    img.name = "cupola_atlas"
    img.colorspace_settings.name = 'sRGB'
    mat = unlit_material("cupola.baked", img)
    glass = glass_material()
    # the game gets only the cupola: remove the station, lamps, helpers
    keep = set()
    for o in bpy.data.collections['cupola'].all_objects:
        keep.add(o.name)
    keep.add('camera.player')
    for o in list(sc.objects):
        if o.name not in keep:
            bpy.data.objects.remove(o)
    for o in list(sc.objects):
        if o.type != 'MESH':
            continue
        if o.name.startswith('pane.'):
            strip(o, 'tex')
            o.data.materials.clear()
            o.data.materials.append(glass)
        else:
            strip(o, 'bake')
            o.data.materials.clear()
            o.data.materials.append(mat)
        for k in ('part',):
            if k in o.keys():
                del o[k]
    col = bl.collection("contract_export")
    cam = bpy.data.objects['camera.player']
    bl.tag(cam, fov_deg=world.VFOV_DEG, pitch_deg=world.PITCH_DEG, aspect_designed="16:9",
           note="the player's eye at the origin; vertical fov in fov_deg")
    contract_common(col)
    from . import cupola as C
    P = C.pitch_matrix()
    hud = P @ bl.look_matrix(C.AX * C.A_TOP, C.AX, (0, 0, 1))
    bl.empty("hud.anchor", col, matrix=hud, size=0.2, plane_distance_m=C.A_TOP,
             note="centre of the centre window's inner face; -Z looks out along the cupola's axis")
    sc["colors"] = ("cupola textures are baked display-referred (exposure %.1f stops, AgX Medium High Contrast): "
                    "draw them unlit with no tone mapping" % render.EXPOSURE)
    sc["exposure_stops"] = render.EXPOSURE
    sc["sun_irradiance"] = 20.0
    out = ctx.asset("cupola.glb")
    gltf_export(out, quality=90)
    bpy.ops.wm.save_as_mainfile(filepath=ctx.path("cupola_export.blend"), compress=True)
