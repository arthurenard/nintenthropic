"""Build the people of Dead of Night: walker.glb, mechanic.glb, survivor.glb, cat.glb.

    /Applications/Blender.app/Contents/MacOS/Blender -b --factory-startup -t 4 \\
        -P art/night/characters/build.py [-- --only walker,cat --quick --blend DIR --out DIR]

Everything - meshes, textures, rigs, clips - is generated by deadlib/ on top
of High Noon's character library (art/western/characters/charlib, imported
read-only); nothing is downloaded. The .glb files land in public/assets/night/.
With --blend each finished scene is also saved (for review.py; git-ignored).
"""
import os
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
REPO = os.path.abspath(os.path.join(HERE, "..", "..", ".."))

import bpy  # noqa: E402

argv = sys.argv[sys.argv.index("--") + 1:] if "--" in sys.argv else []


def arg(name, default=None):
    if name in argv:
        return argv[argv.index(name) + 1]
    return default


ALL = ["walker", "mechanic", "survivor", "cat"]
only = arg("--only", ",".join(ALL)).split(",")
out = arg("--out", os.path.join(REPO, "public", "assets", "night"))
blend_dir = arg("--blend", os.path.join(HERE, "..", "build", "characters"))
quick = "--quick" in argv
outfits = arg("--outfits")

t0 = time.time()
for who in only:
    t = time.time()
    path = os.path.join(out, f"{who}.glb")
    if who == "walker":
        from deadlib import walker
        walker.build(path, size=1024 if quick else 2048, quick=quick, only_outfits=outfits.split(",") if outfits else None)
    elif who == "mechanic":
        from deadlib import mechanic
        mechanic.build(path, size=1024, quick=quick)
    elif who == "survivor":
        from deadlib import survivor
        survivor.build(path, size=1024, quick=quick)
    elif who == "cat":
        from deadlib import cat
        cat.build(path, size=512, quick=quick)
    else:
        print(f"[night] no builder for {who}")
        continue
    if blend_dir:
        os.makedirs(blend_dir, exist_ok=True)
        bpy.ops.wm.save_as_mainfile(filepath=os.path.join(blend_dir, f"{who}.blend"))
    print(f"[night] {who} done in {time.time() - t:.0f}s", flush=True)
print(f"[night] all done in {time.time() - t0:.0f}s", flush=True)
