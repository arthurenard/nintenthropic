"""Build the people of High Noon: bandit.glb, boss.glb, townsfolk.glb, chicken.glb.

    /Applications/Blender.app/Contents/MacOS/Blender -b --factory-startup \\
        -P art/western/characters/build.py [-- --only bandit,boss --out DIR --blend DIR]

Everything - meshes, textures, rig, animation - is generated by the scripts in
charlib/; nothing is downloaded. The .glb files land in public/assets/western/.
With --blend the finished scene of each character is also saved (a build
product, git-ignored) for inspection and the review renders.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
REPO = os.path.abspath(os.path.join(HERE, "..", "..", ".."))

import bpy  # noqa: E402
from charlib import cast  # noqa: E402

argv = sys.argv[sys.argv.index("--") + 1:] if "--" in sys.argv else []


def arg(name, default=None):
    if name in argv:
        return argv[argv.index(name) + 1]
    return default


ALL = ["bandit", "boss", "townsfolk", "chicken"]
only = arg("--only", ",".join(ALL)).split(",")
out = arg("--out", os.path.join(REPO, "public", "assets", "western"))
blend_dir = arg("--blend")

for who in only:
    fn = getattr(cast, f"build_{who}", None)
    if fn is None:
        print(f"[chars] no builder for {who} yet")
        continue
    fn(os.path.join(out, f"{who}.glb"))
    if blend_dir:
        os.makedirs(blend_dir, exist_ok=True)
        bpy.ops.wm.save_as_mainfile(filepath=os.path.join(blend_dir, f"{who}.blend"))
