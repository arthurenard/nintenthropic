"""Export vehicles.glb: each vehicle's parts share one material (the baked
albedo + normal + ORM atlas); the glass has its own plain material the game
replaces. Draco geometry, WebP textures, node extras for the contract; then
the Blender name prefixes are stripped in the GLB (glbtool) so both vehicles
expose the same part names.
"""

import os

import bpy

from charlib.materials import final_material
from glbtool import GLB

from . import assemble


def glass_material(name):
    """Dusty tinted glass, mostly transparent: a sane default the game can
    replace (it adds reflections and cracks)."""
    m = bpy.data.materials.new(name)
    m.use_nodes = True
    nt = m.node_tree
    nt.nodes.clear()
    out = nt.nodes.new('ShaderNodeOutputMaterial')
    b = nt.nodes.new('ShaderNodeBsdfPrincipled')
    b.inputs['Base Color'].default_value = (0.26, 0.29, 0.29, 1.0)
    b.inputs['Roughness'].default_value = 0.06
    b.inputs['Alpha'].default_value = 0.30
    nt.links.new(b.outputs[0], out.inputs['Surface'])
    try:
        m.surface_render_method = 'BLENDED'
    except AttributeError:
        pass
    m.use_backface_culling = False
    return m


def prepare(ob, mat):
    """One material, one UV map, no build-time attributes."""
    me = ob.data
    for uv in list(me.uv_layers):
        if uv.name != "UVMap":
            me.uv_layers.remove(uv)
    for a in list(me.attributes):
        if a.name in ("rand",):
            me.attributes.remove(a)
    me.materials.clear()
    me.materials.append(mat)
    me.polygons.foreach_set("material_index", [0] * len(me.polygons))
    me.update()


def export_all(made, out_dir, work, col, log=print):
    roots = []
    for v, parts, proto in made:
        im = v.images
        mat = final_material(f"{v.name}", im["albedo"], im["normal"], im["orm"], double_sided=True)
        for ob in [p[0] for p in parts] + [proto]:
            prepare(ob, mat)
        root = assemble.assemble(v, parts, proto, col)
        g = bpy.data.objects[f"{v.name}.cab.glass"]
        me = g.data
        if "grain" in me.uv_layers:
            me.uv_layers["grain"].name = "UVMap"
        for a in list(me.attributes):
            if a.name == "rand":
                me.attributes.remove(a)
        me.materials.clear()
        me.materials.append(glass_material(f"{v.name}.glass"))
        log(f"{v.name}: {assemble.triangles(root)} triangles in the node tree")
        roots.append(root)
    for o in bpy.context.view_layer.objects:
        o.select_set(False)
    for r in roots:
        r.select_set(True)
        for c in r.children_recursive:
            c.select_set(True)
    path = os.path.join(out_dir, "vehicles.glb")
    bpy.ops.export_scene.gltf(
        filepath=path, export_format='GLB', use_selection=True, use_visible=False, use_renderable=False,
        export_extras=True, export_cameras=False, export_lights=False, export_yup=True, export_apply=True,
        export_texcoords=True, export_normals=True, export_tangents=False, export_materials='EXPORT',
        export_vertex_color='NONE', export_attributes=False,
        export_image_format='WEBP', export_image_quality=88, export_image_add_webp=False,
        export_draco_mesh_compression_enable=True, export_draco_mesh_compression_level=7,
        export_draco_position_quantization=14, export_draco_normal_quantization=10,
        export_draco_texcoord_quantization=14, export_draco_generic_quantization=12,
        export_animations=False, export_skins=False, export_morph=False, export_unused_images=False,
        export_copyright="Handy - Overwatch Ridge, generated by art/ridge/vehicles/build.py")
    # both vehicles expose the same part names: strip the Blender prefixes
    glb = GLB.load(path)
    prefixes = [v.name + "." for v, _, _ in made]

    def fn(name, parent):
        for p in prefixes:
            if name.startswith(p):
                return name[len(p):]
        return None
    glb.rename_nodes(fn)
    glb.save(path)
    log(f"exported {path}: {os.path.getsize(path) / 1e6:.2f} MB")
    return path
